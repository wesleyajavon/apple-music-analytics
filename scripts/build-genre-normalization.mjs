function buildKeyToCanonical(groups) {
  const m = new Map();
  for (const g of groups) {
    const c = g.canonical.trim();
    m.set(normKey(c), c);
    for (const a of g.aliases) {
      m.set(normKey(a), c);
    }
  }
  return m;
}

function enrichFromDbSample(groups, samplePath) {
  if (!fs.existsSync(samplePath)) return groups;
  const sample = JSON.parse(fs.readFileSync(samplePath, 'utf8'));
  const keyToCanon = buildKeyToCanonical(groups);
  /** canonical -> Set of exact strings */
  const byCanon = new Map();
  for (const g of groups) {
    const set = new Set();
    set.add(g.canonical);
    g.aliases.forEach((a) => set.add(a));
    byCanon.set(g.canonical, set);
  }

  for (const row of sample) {
    const raw = row.g;
    if (raw == null || !String(raw).trim()) continue;
    const canon = keyToCanon.get(normKey(raw));
    if (!canon) continue;
    byCanon.get(canon).add(raw);
  }

  return groups.map((g) => {
    const raw = [...byCanon.get(g.canonical)].filter(
      (s) => normKey(s) !== normKey(g.canonical)
    );
    const seen = new Set();
    const aliases = [];
    for (const s of raw.sort((a, b) => a.localeCompare(b))) {
      const k = normKey(s);
      if (seen.has(k)) continue;
      seen.add(k);
      aliases.push(s);
    }
    return { canonical: g.canonical, aliases };
  });
}

function validate(groups) {
  const seen = new Map();
  for (const g of groups) {
    const c = g.canonical.trim();
    const keys = [normKey(c), ...g.aliases.map(normKey)].filter(Boolean);
    for (const k of keys) {
      if (seen.has(k)) {
        throw new Error(`Conflit: "${k}" → "${seen.get(k)}" et "${c}"`);
      }
      seen.set(k, c);
    }
  }
}

